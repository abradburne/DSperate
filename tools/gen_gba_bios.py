#!/usr/bin/env python3
# Regenerates src/core/gba/bios/cultbios_data.cpp from a Cult-of-GBA BIOS checkout:
#   git clone https://github.com/Cult-of-GBA/BIOS cult-bios && cd cult-bios && git checkout a30e9a9
#   patch -p1 < .../src/core/gba/bios/cultbios-sqrt0.patch
#   arm-none-eabi-as entrypoint.s -mcpu=arm7tdmi -o e.o && arm-none-eabi-objcopy e.o bios.bin -O binary
#   tools/gen_gba_bios.py cult-bios/bios.bin > src/core/gba/bios/cultbios_data.cpp
import sys
d = open(sys.argv[1], 'rb').read()
assert len(d) == 16384, len(d)
out = ['// SPDX-License-Identifier: MIT',
       '// Cult-of-GBA BIOS: a free Game Boy Advance replacement BIOS by DenSinH and',
       '// fleroviux (https://github.com/Cult-of-GBA/BIOS, commit a30e9a9, 2025-04-06),',
       '// with cultbios-sqrt0.patch (Sqrt(0) = 0). See LICENSE.cult-bios.',
       '// Built with arm-none-eabi-as -mcpu=arm7tdmi + objcopy -O binary.',
       '//',
       '// Generated by tools/gen_gba_bios.py. Do not edit by hand.',
       '#include "core/gba/bios/cultbios.h"', '', 'namespace ds::gba {',
       'const u8 kCultBios[16384] = {']
for i in range(0, len(d), 16):
    out.append('  ' + ', '.join('0x%02x' % b for b in d[i:i+16]) + ',')
out += ['};', '', '} // namespace ds::gba', '']
sys.stdout.write('\n'.join(out))
